// Generates supabase/seed.sql from the demo dataset in js/data.js.
// All dates are written relative to "today" in the shop's timezone, so the demo always looks current when you run seed.sql.
//   node supabase/make-seed.js
const fs = require('fs');
const path = require('path');
global.window = {};
require(path.join(__dirname, '..', 'js', 'data.js'));
const RR = global.window.RR, raw = RR.demoRaw();

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const day = (iso) => `(shop_today() + ${RR.daysBetween(RR.DEMO_TODAY, iso.slice(0, 10))})`;
const ts = (iso) => `(${day(iso)} + time '${iso.length > 10 ? iso.slice(11, 16) : '09:00'}')`;
const arr = (a) => 'array[' + a.map(q).join(', ') + ']';
const insert = (head, rows) => { out.push(head); out.push(rows.join(',\n') + ';'); };
const out = [];
out.push('-- Demo data for Pratishtha Bridal (generated by supabase/make-seed.js). Dates are relative to today.');
out.push('-- Safe to run once on an empty database. It does NOT create users: sign up the owner first, then run this.');
out.push('begin;');

out.push(`update shop_settings set shop_name=${q(raw.settings.shopName)}, address=${q(raw.settings.address)}, phone=${q(raw.settings.phone)}, upi_id=${q(raw.settings.upi)}, salon_terms=${arr(raw.settings.salonTerms)} where id=1;`);

insert('insert into outfits (piece_no, name, category, size, rent_per_day, deposit, color1, color2, status, note) values',
  raw.outfits.map((o) => `  (${o.id}, ${q(o.name)}, ${q(o.cat)}, ${q(o.size)}, ${o.rent}, ${o.dep}, ${q(o.c1)}, ${q(o.c2)}, ${q(o.status)}, ${q(o.note)})`));

insert('insert into customers (id, name, phone, city, id_proof) values',
  raw.customers.map((c) => `  (${c.id}, ${q(c.name)}, ${q(c.phone)}, ${q(c.city)}, ${q(c.idProof)})`));

// ---- bridal salon: artists, price list, weddings (must exist before the bookings that point at them) ----
insert('insert into artists (id, name, phone, skill, active) values', raw.artists.map((a) => `  (${a.id}, ${q(a.name)}, ${q(a.phone)}, ${q(a.skill)}, ${a.active})`));
insert('insert into salon_services (id, name, category, price, minutes, active) values', raw.services.map((x) => `  (${x.id}, ${q(x.name)}, ${q(x.category)}, ${x.price}, ${x.minutes}, ${x.active})`));
insert('insert into weddings (id, customer_id, groom_name, wedding_date, venue, city, status, discount, notes, created_at) values',
  raw.weddings.map((w) => `  (${w.id}, ${w.customerId}, ${q(w.groom)}, ${day(w.date)}, ${q(w.venue)}, ${q(w.city)}, ${q(w.status)}, ${w.discount}, ${q(w.notes)}, ${ts(w.createdAt)})`));
insert('insert into wedding_events (id, wedding_id, kind, title, event_date, start_time, end_time, venue, artist_id, people, notes, done) values',
  raw.wevents.map((e) => `  (${e.id}, ${e.wedding}, ${q(e.kind)}, ${q(e.title)}, ${day(e.date)}, ${q(e.start)}, ${q(e.end)}, ${q(e.venue)}, ${e.artist == null ? 'null' : e.artist}, ${e.people}, ${q(e.notes)}, ${e.done})`));
insert('insert into wedding_items (id, wedding_id, event_id, service_id, description, qty, price) values',
  raw.witems.map((i) => `  (${i.id}, ${i.wedding}, ${i.event == null ? 'null' : i.event}, ${i.service == null ? 'null' : i.service}, ${q(i.desc)}, ${i.qty}, ${i.price})`));
insert('insert into wedding_payments (wedding_id, amount, mode, note, by_name, created_at) values',
  raw.wpayments.map((p) => `  (${p.wedding}, ${p.amount}, ${q(p.mode)}, ${q(p.note)}, ${q(p.who || '')}, ${ts(p.at)})`));
insert('insert into wedding_tasks (id, wedding_id, title, due, done) values',
  raw.wtasks.map((t) => `  (${t.id}, ${t.wedding}, ${q(t.title)}, ${t.due ? day(t.due) : 'null'}, ${t.done})`));

insert('insert into bookings (id, piece_no, customer_id, from_date, to_date, status, rent, deposit, wedding_id, created_at) values',
  raw.bookings.map((b) => `  (${b.no}, ${b.outfit}, ${b.customerId}, ${day(b.from)}, ${day(b.to)}, ${q(b.status)}, ${b.rent}, ${b.deposit}, ${b.weddingId || 'null'}, ${ts(b.createdAt)})`));

insert('insert into payments (booking_id, type, mode, amount, created_at) values',
  raw.payments.map((p) => `  (${p.booking}, ${q(p.type)}, ${q(p.mode)}, ${p.amount}, ${ts(p.at)})`));

insert('insert into booking_events (booking_id, kind, message, created_at) values',
  raw.events.map((e) => `  (${e.booking}, ${q(e.kind)}, ${q(e.message)}, ${ts(e.at)})`));

insert('insert into returns (booking_id, returned_on, deposit_held, late_fee, damage_total, other_deduction, net_refund, mode, next_status, notes) values',
  raw.returned.map((r) => `  (${r.booking}, ${day(r.date)}, ${r.depositHeld}, ${r.lateFee}, ${r.damage}, ${r.other}, ${r.net}, ${q(r.mode)}, ${q(r.next)}, ${q(r.notes)})`));

out.push("select setval(pg_get_serial_sequence('customers', 'id'), (select max(id) from customers));");
out.push("select setval(pg_get_serial_sequence('bookings', 'id'), greatest(1100, (select max(id) from bookings)));");
['artists', 'salon_services', 'wedding_events', 'wedding_items', 'wedding_tasks', 'wedding_payments'].forEach((t) => out.push(`select setval(pg_get_serial_sequence('${t}', 'id'), (select max(id) from ${t}));`));
out.push("select setval(pg_get_serial_sequence('weddings', 'id'), greatest(5001, (select max(id) from weddings)));");
out.push('commit;');
fs.writeFileSync(path.join(__dirname, 'seed.sql'), out.join('\n') + '\n');
console.log('seed.sql written:', raw.outfits.length, 'outfits,', raw.customers.length, 'customers,', raw.bookings.length, 'bookings,', raw.payments.length, 'payments,', raw.weddings.length, 'weddings,', raw.wevents.length, 'functions');
